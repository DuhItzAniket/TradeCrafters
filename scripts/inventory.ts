import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { directorySource, micDirectory } from "@tradecrafters/market-catalog";
import { micRecordSchema } from "@tradecrafters/domain/catalog";
import {
  inventoryAssessment,
  inventoryClassificationInputs,
} from "../packages/domain/src/inventory";

const root = new URL("../", import.meta.url);
const manifestUrl = new URL(
  "packages/market-catalog/data/inventory-review-2026-10-24.json",
  root,
);
const outputs = {
  csv: new URL("docs/research/evidence/inventory-2026-10-24.csv", root),
  summary: new URL("docs/research/evidence/inventory-2026-10-24.md", root),
};
const cell = (value: unknown) => {
  const text = String(value);
  const safe = /^[=+\-@\t\r]/.test(text) ? `'${text}` : text;
  return `"${safe.replaceAll('"', '""')}"`;
};
async function main() {
  const [command, ...extra] = process.argv.slice(2);
  if (extra.length || !["report", "check", "publish"].includes(command))
    throw Error();
  const input = JSON.parse(await readFile(manifestUrl, "utf8"));
  const records = micDirectory.map((row) => micRecordSchema.parse(row));
  // Historical artifact is pinned to its review timestamp. Live publication
  // separately checks the actual clock; expired reviews never become current.
  const result = inventoryAssessment(
    input,
    records,
    directorySource,
    new Date(input.reviewedAt),
  );
  const columns = [
    "mic",
    "operatingMic",
    "kind",
    "name",
    "country",
    "status",
    "classification",
    "reviewState",
    "scope",
    "evidenceRef",
    "reviewedAt",
    "expiresAt",
  ] as const;
  const csv =
    [
      columns.join(","),
      ...result.rows.map((row) =>
        columns.map((key) => cell(row[key])).join(","),
      ),
    ].join("\n") + "\n";
  const countBy = (key: "kind" | "status") =>
    Object.entries(
      result.rows.reduce<Record<string, number>>((counts, row) => {
        counts[row[key]] = (counts[row[key]] || 0) + 1;
        return counts;
      }, {}),
    )
      .sort()
      .map(([key, count]) => `${key}: ${count}`)
      .join("; ");
  const summary = `# Worldwide inventory review — 24 October 2026

Generated by \`npm run inventory -- report\`; verify with \`npm run inventory -- check\`. Historical assessment as of **${result.asOf}**, expiring **${result.review.expiresAt}**. This is agent research from public primary sources, not independent owner or student attestation.

## Reference and counting

- Source: [ISO 10383 Registration Authority](https://www.iso20022.org/market-identifier-codes), publication ${result.review.snapshotId}, changes effective **${result.review.changesEffectiveOn}**. At the assessment time this is an upcoming reference; the actual prior effective baseline remains missing.
- Source content SHA-256: \`${result.review.sourceHash}\` (canonical normalized records, not raw CSV bytes).
- All **${result.totalReferenceRecords} MIC records** remain in [the complete CSV](inventory-2026-10-24.csv). ${countBy("kind")}. ${countBy("status")}.
- **${result.counts.cash_equity} cash-equity-presence records**, **${result.counts.other_facility} other facilities**, **${result.counts.unknown} unknown**. The ${result.reviewedRows} reviewed rows include two deliberately unresolved assessments. This is a partial review, not the complete world exchange denominator.
- Known cash-equity presence spans **${result.cashEquityOperatingGroups} distinct operating MIC groups**. Do not add operating and child-segment counts and call that a count of exchanges. An operating presence review does not classify all its segments or instruments.
- **${result.supplementalCandidates} supplemental identity candidates** are kept separately from MIC counts. They are not invented MICs or verified additional members of a complete denominator.
- Real simulation enabled: **0**. Listings, history/EOD/delayed/live, actions, FX and display/simulation/retention/replay permissions remain unreviewed for every real venue. No provider directory or public page establishes an account entitlement.

## Reviewed batch

| MIC | Region | Scope / assessment | Evidence and remaining work |
| --- | --- | --- | --- |
${result.review.reviews.map((row) => `| ${row.mic} | ${row.region} | ${row.scope}; ${row.classification} | [Primary source](${row.evidenceRef}). ${row.evidenceSummary} Next: ${row.followUp} |`).join("\n")}

## Supplemental identity gaps

| Candidate | Country | Evidence / gap | Next action |
| --- | --- | --- | --- |
${result.review.supplemental.map((row) => `| ${row.name} (\`${row.id}\`) | ${row.country} | [Primary source](${row.evidenceRef}). ${row.evidenceSummary} Snapshot country rows: ${row.referenceCountryRecords}. | ${row.followUp} |`).join("\n")}

## Data-quality findings and limits

| Risk | Evidence | Severity / confidence | Handling |
| --- | --- | --- | --- |
| Future source applied early | Publication 12 October; implementation 26 October; assessment precedes implementation | High / high | Preserve the upcoming label; no fabricated September baseline or current execution state. |
| Mixed grain and group inheritance | XTKS is a segment of XJPX; XASX contains the distinct XSFE derivatives segment | High / high | Bind each review to exact identity hashes; keep group presence separate from segment/product eligibility and deduplicate operating groups. |
| Incomplete denominator | ${result.counts.unknown}/${result.totalReferenceRecords} records remain unknown (${((100 * result.counts.unknown) / result.totalReferenceRecords).toFixed(2)}%); ${result.supplementalCandidates} supplemental candidates have unresolved mappings | High / high within this snapshot | Retain every row and explicit follow-up; do not report a global trading-coverage percentage. |
| Unavailable direct evidence | Direct JSE page returned 403; ESX direct pages timed out, while primary indexed text was available | Medium / medium | JSE stays unknown; ESX stays a supplemental mapping/source-verification gap. No access bypass was attempted. |
| Evidence staleness | Classification expires on ${result.review.expiresAt}; BRVM support is a dated July report | Medium / high | Revalidate on renewal; future/expired reviews resolve to unknown; source observations are not real-time prices. |

Identity/source hashes, strict schemas, duplicate checks, expiring assessments and supplemental-count reconciliation are automated in \`tests/inventory.test.ts\`. The generator and checked-in manifest make the transformations inspectable; tests cannot prove that an external site remains unchanged. CSV values are quoted and formula-leading text is prefixed for spreadsheet safety; original definitions remain in the source JSON.

Classification publication is a separate, explicit operator operation. This artifact alone does not change a hosted database or enable data. See [operator workflow](../../implementation/inventory-review.md). All gaps remain tracked in [#9](https://github.com/DuhItzAniket/TradeCrafters/issues/9), alongside [M5 #7](https://github.com/DuhItzAniket/TradeCrafters/issues/7).
`;
  if (command === "report") {
    await writeFile(outputs.csv, csv);
    await writeFile(outputs.summary, summary);
  } else if (command === "check") {
    if (
      (await readFile(outputs.csv, "utf8")) !== csv ||
      (await readFile(outputs.summary, "utf8")) !== summary
    )
      throw Error();
  } else {
    const current = inventoryAssessment(
      input,
      records,
      directorySource,
      new Date(),
    );
    if (current.reviewState !== "current" || !process.env.OPERATOR_DATABASE_URL)
      throw Error();
    const entries = inventoryClassificationInputs(current.review);
    process.env.DATABASE_URL = process.env.OPERATOR_DATABASE_URL;
    const { seedCatalogSnapshot, reviewVenueClassification } =
      await import("@tradecrafters/database/catalog");
    const { closePool } = await import("@tradecrafters/database");
    let completed = 0;
    try {
      // Verify the persisted immutable snapshot before any classification write.
      await seedCatalogSnapshot();
      for (const entry of entries) {
        await reviewVenueClassification(entry);
        completed++;
      }
    } finally {
      await closePool();
      console.log(
        `Classification rows completed: ${completed}/${entries.length}. Identical retry is safe; no capability publication is performed.`,
      );
    }
  }
  console.log(
    JSON.stringify({
      command,
      referenceRecords: result.totalReferenceRecords,
      reviewedRows: result.reviewedRows,
      classification: result.counts,
      supplementalCandidates: result.supplementalCandidates,
      realSimulationEnabled: 0,
      artifact:
        command === "publish" ? undefined : fileURLToPath(outputs.summary),
    }),
  );
}
main().catch(() => {
  console.error(
    "Inventory operation rejected. Check source hashes, review dates, artifacts and operator configuration; details hidden.",
  );
  process.exitCode = 1;
});
